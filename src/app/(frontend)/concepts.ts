export function pickConcepts(count: number, excluded: string[] = []) {
  const excludedConcepts = new Set(excluded)
  const candidates = AVAILABLE_CONCEPTS.filter(
    (concept) => !excludedConcepts.has(concept),
  )

  for (let index = candidates.length - 1; index > 0; index -= 1) {
    const randomIndex = Math.floor(Math.random() * (index + 1))
    ;[candidates[index], candidates[randomIndex]] = [
      candidates[randomIndex],
      candidates[index],
    ]
  }

  return candidates.slice(0, count)
}
